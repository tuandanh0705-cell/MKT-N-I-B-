export const STICKER_CONTENT_PREFIX = "🎭 [Sticker] ";

export function formatStickerMessageContent(stickerName: string): string {
  const clean = stickerName.trim().slice(0, 60) || "Sticker";
  return `${STICKER_CONTENT_PREFIX}${clean}`;
}

export function isBuiltInStickerUrl(url: string | null | undefined): boolean {
  if (!url) return false;
  return /^\/stickers\/[a-z0-9_-]+\.(svg|png|webp|gif)$/i.test(url.trim());
}

export function isImageOrStickerAttachment(
  url: string | null | undefined
): boolean {
  if (!url) return false;
  const trimmed = url.trim();
  return (
    isBuiltInStickerUrl(trimmed) ||
    /^data:image\/(png|jpeg|jpg|webp|gif);base64,/i.test(trimmed) ||
    /\.(png|jpe?g|webp|gif|svg)(\?.*)?$/i.test(trimmed)
  );
}

export function isStickerMessage(
  content: string | null | undefined,
  attachmentUrl: string | null | undefined
): boolean {
  if (!content || !attachmentUrl) return false;
  return content.startsWith(STICKER_CONTENT_PREFIX);
}

export function getStickerNameFromContent(content: string): string {
  if (!content.startsWith(STICKER_CONTENT_PREFIX)) return "Sticker";
  return content.slice(STICKER_CONTENT_PREFIX.length).trim() || "Sticker";
}

/**
 * Kiểm tra xem tin nhắn chỉ chứa 1-3 emoji (không có chữ/số/link) để phóng to sinh động như Messenger/Zalo.
 */
export function isPureEmojiMessage(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed || trimmed.length > 24) return false;
  // Loại bỏ khoảng trắng & ký tự nối ZWJ / Variation Selector
  const stripped = trimmed.replace(/\s+/g, "");
  if (!stripped) return false;
  // Không chứa chữ cái, chữ số hay dấu câu thường
  if (/[a-zA-Z0-9À-ỹ.,!?;:@#/_-]/.test(stripped)) return false;
  try {
    const emojiMatches = stripped.match(/\p{Extended_Pictographic}/gu);
    if (!emojiMatches || emojiMatches.length === 0 || emojiMatches.length > 3) {
      return false;
    }
    const remainder = stripped
      .replace(/\p{Extended_Pictographic}/gu, "")
      .replace(/[\u200d\ufe0f\u20e3\u{1f3fb}-\u{1f3ff}]/gu, "");
    return remainder.length === 0;
  } catch {
    return false;
  }
}

